-- ElectroStore currency migration: USD sample prices -> realistic LKR values.
-- Historical orders and order_items are intentionally unchanged because their original currency is ambiguous.
USE electrostore;
START TRANSACTION;
UPDATE products SET price = CASE id
  WHEN 1 THEN 389000 WHEN 2 THEN 239000 WHEN 3 THEN 45000 WHEN 4 THEN 179000
  WHEN 5 THEN 69900 WHEN 6 THEN 59900 WHEN 7 THEN 479000 WHEN 8 THEN 99000
  WHEN 9 THEN 29000 WHEN 10 THEN 99000 WHEN 11 THEN 269000 WHEN 12 THEN 24900
  WHEN 13 THEN 329000 WHEN 14 THEN 19900 WHEN 15 THEN 289000 WHEN 16 THEN 74900
  WHEN 17 THEN 569000 WHEN 18 THEN 189000 WHEN 19 THEN 34900 WHEN 20 THEN 229000
  WHEN 21 THEN 24900 WHEN 22 THEN 89900 WHEN 23 THEN 169000 WHEN 24 THEN 59900
  ELSE price END
WHERE id BETWEEN 1 AND 24;
COMMIT;
